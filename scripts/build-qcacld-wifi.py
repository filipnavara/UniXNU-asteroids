#!/usr/bin/env python3
"""Compile the qcacld WiFi module (drivers/QcacldWifi: qcacld-3.0 on the icnss backend) to kernel objects for the board build.
Usage: build-qcacld-wifi.py <QcacldWifi dir> <output dir>
Prints one line "OBJ <path>" per object, like build-ath11k-wifi.py, so the board build links either module.
- The runtime (lx_rt, cfg80211, QMI, QRTR, the station/control path, hostap crypto) comes from the Ath11kWifi module, compiled by
  build-ath11k-wifi.py in its runtime-only mode (no ath11k, mac80211 or their glue).
- qcacld: the vendor wlan tree (QCACLD_VENDOR_WLAN, default <workspace>/ref/nothing-kernel/vendor/qcom/opensource/wlan) is copied and
  patched (tools/prepare.sh), its object list taken from the vendor Kbuild (tools/objlist.sh), and compiled with the kernel's target
  (tools/check.py board).
- Every global name of both gets the prefix nwk_ except the board's entry points (wifi_entry_points.KEEP)."""
import hashlib, json, os, shutil, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from kernel_target import TRIPLE
from wifi_entry_points import KEEP

here = Path(__file__).resolve().parent
module = Path(sys.argv[1]).resolve()
out = Path(sys.argv[2]).resolve()
ath11k = module.parent / 'Ath11kWifi'
workspace = module.parents[2]   # <workspace>/UniXNU-asteroids/drivers/QcacldWifi (the board build runs a copy of this script)
vendor = Path(os.environ.get('QCACLD_VENDOR_WLAN') or workspace / 'ref/nothing-kernel/vendor/qcom/opensource/wlan').resolve()
if not (vendor / 'qcacld-3.0/Kbuild').is_file():
    raise SystemExit(f'{vendor}: no qcacld-3.0 tree (set QCACLD_VENDOR_WLAN)')
out.mkdir(parents=True, exist_ok=True)
(out / 'build-report.json').unlink(missing_ok=True)
# The device's WCNSS_qcom_cfg.ini (vendor partition, etc/wifi/qca6750): qcacld does not load without it. Not in the repository: the
# module embeds a local copy (QCACLD_INI, default <workspace>/stock/vendor-wifi/WCNSS_qcom_cfg.ini) and serves it by name.
ini = Path(os.environ.get('QCACLD_INI') or workspace / 'stock/vendor-wifi/WCNSS_qcom_cfg.ini').resolve()
if not ini.is_file():
    raise SystemExit(f'{ini}: the device\'s WCNSS_qcom_cfg.ini is needed (set QCACLD_INI)')
gen = module / 'out/gen'
gen.mkdir(parents=True, exist_ok=True)
data = ini.read_bytes()
(gen / 'nw_embedded_files.c').write_text(
    '/* Generated by build-qcacld-wifi.py: files the module serves itself (src/nw_qcacld.c). */\n#include <stddef.h>\n'
    'struct nw_embedded_file { const char *name; const unsigned char *data; size_t size; };\n'
    f'static const unsigned char ini[{len(data)}] = {{' + ','.join(str(b) for b in data) + '};\n'
    'const struct nw_embedded_file nw_embedded_files[] = { { "WCNSS_qcom_cfg.ini", ini, sizeof ini }, { 0, 0, 0 } };\n')


def objects(text):
    return [Path(line.split(' ', 1)[1]) for line in text.splitlines() if line.startswith('OBJ ')]


runtime = objects(subprocess.check_output([sys.executable, str(here / 'build-ath11k-wifi.py'), str(ath11k), str(out / 'runtime')],
                                          env={**os.environ, 'NW_WIFI_RUNTIME_ONLY': '1'}, text=True))
if not runtime:
    raise SystemExit('the runtime built no objects')
subprocess.run(['sh', str(module / 'tools/prepare.sh'), str(vendor)], check=True, stdout=subprocess.DEVNULL)
subprocess.run(['sh', str(module / 'tools/objlist.sh'), str(module / 'out/wlan')], check=True, stdout=subprocess.DEVNULL)
qcacld_dir = out / 'qcacld'
shutil.rmtree(qcacld_dir, ignore_errors=True)
qcacld = objects(subprocess.check_output([sys.executable, str(module / 'tools/check.py'), str(module / 'out/wlan'), 'board',
                                          str(qcacld_dir), TRIPLE], text=True))
if not qcacld:
    raise SystemExit('qcacld built no objects')

llvm = Path(subprocess.run(['brew', '--prefix', 'llvm'], check=True, capture_output=True, text=True).stdout.strip()) / 'bin'
raw = [('runtime', o) for o in runtime] + [('qcacld', o) for o in qcacld]
names = set()
for _, o in raw:
    r = subprocess.run([str(llvm / 'llvm-nm'), '-g', '--defined-only', str(o)], check=True, capture_output=True, text=True)
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] not in KEEP:
            names.add(parts[2])
mapping = out / 'rename.txt'
mapping.write_text(''.join(f'{n} _nwk{n}\n' for n in sorted(names)))
final = out / 'objects'
shutil.rmtree(final, ignore_errors=True)
final.mkdir()
result = []
for kind, o in raw:
    dest = final / f'{kind}__{o.name}'
    shutil.copyfile(o, dest)
    subprocess.run([str(llvm / 'llvm-objcopy'), f'--redefine-syms={mapping}', str(dest)], check=True)
    result.append(dest)
(out / 'build-report.json').write_text(json.dumps({
    'runtime': 'mainline', 'driver': 'qcacld-3.0 (qca6750, icnss backend)', 'hardware_verified': False,
    'vendor': str(vendor), 'ini_sha256': hashlib.sha256(data).hexdigest(), 'patch_sha256': hashlib.sha256((module / 'patches/qcacld-port.patch').read_bytes()).hexdigest(),
    'objects': [str(o) for o in result],
}, indent=2) + '\n')
for o in result:
    print(f'OBJ {o}')
