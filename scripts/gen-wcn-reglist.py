#!/usr/bin/env python3
"""Generate the WCN6750 data-path register list for the register-state diff (wifi-regdump, tools/nwregdump).

Reads Qualcomm's fw-api register headers for qca6750 (fw-api/hw/qca6750/v1: reo, wbm, mac_tcl, wfss_ce *_reg_seq_hwioreg.h, not part
of this repository) and keeps the configuration and ring pointer registers: names with STATUS, DEBUG, FIFO, POP, PEEK, TESTBUS, CLEAR,
CMD, SNAPSHOT, _RD_, EVENT, COUNTER, _CNT or HISTORY are left out, since reading those can have side effects or says nothing about the
setup. Offsets are the chip's (UMAC 0xa00000.., copy engines 0x1b80000..), the way ath11k_hif_read32 takes them; WCN6750 reaches UMAC
through static window 1 and the copy engines through window 2 of the register window.

    gen-wcn-reglist.py FW_API_QCA6750_V1_DIR

writes drivers/Ath11kWifi/src/nw_wcn_regs.h (the offsets) and drivers/Ath11kWifi/tools/wcn-regs.txt (offset and name, for
scripts/diff-wcn-regs.py).
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
skip = re.compile(r"STATUS|DEBUG|FIFO|POP|PEEK|TESTBUS|CLEAR|CMD|SNAPSHOT|_RD_|EVENT|COUNTER|_CNT|HISTORY")
pattern = re.compile(r"#define HWIO_(\w+)_ADDR\(x\)\s+\(x\+(0x[0-9a-fA-F]+)\)")


def regs(name):
    out = []
    for reg, off in pattern.findall((src / name).read_text(errors="replace")):
        if not skip.search(reg):
            out.append((int(off, 16), reg))
    return out


table = []
for base, name in ((0xa34000, "wbm_reg_seq_hwioreg.h"), (0xa38000, "reo_reg_seq_hwioreg.h"), (0xa44000, "mac_tcl_reg_seq_hwioreg.h")):
    table += [(base + off, reg) for off, reg in regs(name)]
# The copy engines: the header names only two registers, but every channel's source and destination ring is a standard SRNG
# (R0 at the ring's base: base LSB/MSB, ID/size, status, MISC flags, interrupt setup, MSI; R2 at +0x400: head and tail pointers).
ce = regs("wfss_ce_reg_seq_hwioreg.h")
for channel in range(12):
    for side, kind in ((0, "SRC"), (0x1000, "DST")):
        base = 0x1b80000 + channel * 0x2000 + side
        named = {off: reg.replace("WFSS_CE_CHANNEL_", "") for off, reg in ce if f"_{kind}_" in reg}
        for off in list(range(0, 0x60, 4)) + [0x400, 0x404] + list(named):
            table.append((base + off, f"CE{channel}_{named.get(off, f'{kind}_+{off:03x}')}"))
table = sorted({off: reg for off, reg in sorted(table, key=lambda t: '+' not in t[1])}.items())  # one name per offset, named first

header = root / "drivers/Ath11kWifi/src/nw_wcn_regs.h"
lines = ["/* Generated by scripts/gen-wcn-reglist.py from Qualcomm's fw-api qca6750 register headers: the WCN6750 data-path",
         " * configuration and ring pointer registers (chip offsets) that wifi-regdump and tools/nwregdump read. */",
         "#define NW_WCN_REGS %d" % len(table),
         "static const unsigned int nw_wcn_regs[NW_WCN_REGS] = {"]
for i in range(0, len(table), 8):
    lines.append("\t" + " ".join(f"0x{off:07x}," for off, _ in table[i:i + 8]))
lines.append("};")
header.write_text("\n".join(lines) + "\n")
(root / "drivers/Ath11kWifi/tools/wcn-regs.txt").write_text("".join(f"{off:07x} {reg}\n" for off, reg in table))
print(len(table), "registers ->", header)
